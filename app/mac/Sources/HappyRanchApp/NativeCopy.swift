    @MainActor static func phaseMessage(_ phase: HomeInviteModel.Phase, locale: AppLocalePreference) -> String {
        switch phase {
        case .idle: return NativeCopy.idle.text(locale: locale)
        case .checkingSavedAccess: return NativeCopy.checkingSavedAccess.text(locale: locale)
        case .validating: return NativeCopy.validatingInvite.text(locale: locale)
        case .joining: return NativeCopy.joiningNetwork.text(locale: locale)
        case .pairing: return NativeCopy.pairing.text(locale: locale)
        case .awaitingApproval: return NativeCopy.awaitingLinuxApproval.text(locale: locale)
        case .saving: return NativeCopy.savingAccess.text(locale: locale)
        case .opening: return NativeCopy.openingRuntime.text(locale: locale)
        case .readyToSwitch: return NativeCopy.readyToSwitch.text(locale: locale)
        case .connected: return NativeCopy.connected.text(locale: locale)
        case .runtimeBusy: return NativeCopy.busy.text(locale: locale)
        case .stopping: return NativeCopy.closingSession.text(locale: locale)
        case .failed(let failure): return localize(failure.localizedDescription, locale: locale)
        case .keychain(let failure): return localize(failure.localizedDescription, locale: locale)
        }
    }

    /// Existing model messages also feed diagnostics. Translate only known
    /// app-owned prose at the native rendering boundary, preserving unknown
    /// errors/codes and the original dynamic diagnostic suffix byte-for-byte.
    @MainActor static func localize(_ value: String) -> String {
        localize(value, locale: .shared)
    }

    @MainActor static func localize(_ value: String, locale: AppLocalePreference) -> String {
        if let copy = NativeCopy(rawValue: value) { return copy.text(locale: locale) }
        for copy in [NativeCopy.connectionFailed, .unexpectedError, .errorDetail, .launchFailed, .stopIncomplete] {
            let prefix = String(copy.rawValue.dropLast("{value}".count))
            if value.hasPrefix(prefix) {
                return copy.format(value: String(value.dropFirst(prefix.count)), locale: locale)
            }
        }
        return value
    }
